async (page) => {
  const checks=[];
  const verify=async (name, predicate) => { if (!await predicate()) throw new Error(name); checks.push(name); };
  await page.setViewportSize({width:390,height:844});
  await page.keyboard.press('Escape');
  await verify('mobile close restores launcher focus',()=>page.getByRole('button',{name:'Open portal assistant',exact:true}).evaluate(el=>document.activeElement===el));
  await page.getByRole('button',{name:'Open portal assistant',exact:true}).click();
  await page.getByRole('button',{name:'Clear conversation',exact:true}).click();
  await verify('clearing restores welcome',()=>page.getByRole('heading',{name:'How can I help?',exact:true}).isVisible());
  await page.emulateMedia({reducedMotion:'reduce'});
  await verify('reduced motion disables panel animation',()=>page.getByRole('dialog').evaluate(el=>getComputedStyle(el).animationName==='none'));
  let held;
  await page.route('**/api/v1/assistant/messages',route=>{held=route;});
  await page.getByRole('textbox').fill('How does screening work?');
  await page.getByRole('textbox').press('Enter');
  await page.getByRole('status',{name:'Assistant is thinking',exact:true}).waitFor();
  await page.screenshot({path:'output/playwright/assistant-premium-thinking.png'});
  await verify('pending request disables sending',()=>page.getByRole('button',{name:'Send message',exact:true}).isDisabled());
  await held.fulfill({status:429,json:{message:'Too many requests'}});
  await page.getByRole('alert').waitFor();
  await page.screenshot({path:'output/playwright/assistant-premium-error.png'});
  await page.unroute('**/api/v1/assistant/messages');
  await page.getByRole('button',{name:'Clear conversation',exact:true}).click();
  await page.setViewportSize({width:390,height:400});
  await verify('short mobile viewport keeps composer visible',()=>page.getByRole('textbox').evaluate(el=>{const r=el.getBoundingClientRect();return r.y>=0 && r.bottom<=innerHeight;}));
  await page.screenshot({path:'output/playwright/assistant-premium-short-mobile.png'});
  await page.setViewportSize({width:720,height:480});
  await verify('200 percent equivalent reflow fits panel',()=>page.getByRole('dialog').evaluate(el=>{const r=el.getBoundingClientRect();return r.x>=0&&r.y>=0&&r.right<=innerWidth&&r.bottom<=innerHeight&&el.scrollWidth===el.clientWidth;}));
  await page.screenshot({path:'output/playwright/assistant-premium-200-percent-reflow.png'});
  let available=false;
  await page.route('**/api/v1/assistant/status',route=>route.fulfill({json:{available,disclaimer:'This assistant explains portal services. It does not provide medical advice or emergency care.'}}));
  await page.reload();
  await page.getByRole('button',{name:'Open portal assistant',exact:true}).click();
  await page.getByText('Currently unavailable',{exact:true}).waitFor();
  await verify('offline state disables input',()=>page.getByRole('textbox').isDisabled());
  await page.screenshot({path:'output/playwright/assistant-premium-unavailable.png'});
  available=true;
  await page.getByRole('button',{name:'Retry',exact:true}).click();
  await page.getByText('Ready to help',{exact:true}).waitFor();
  await verify('retry enables input',()=>page.getByRole('textbox').isEnabled());
  await page.unrouteAll();
  const user={id:17,fullName:'Preview Staff',email:'staff@example.test',roles:['ROLE_CENTER_MANAGER']};
  await page.route('**/api/v1/**',async route=>{
    const path=new URL(route.request().url()).pathname;
    if(path.endsWith('/auth/refresh'))return route.fulfill({json:{token:'ui-preview-only',user}});
    if(path.endsWith('/auth/me'))return route.fulfill({json:user});
    if(path.endsWith('/assistant/status'))return route.fulfill({json:{available:true,personalizedFeaturesAvailable:true,disclaimer:'This assistant explains portal services. It does not provide medical advice or emergency care.'}});
    return route.fulfill({json:[]});
  });
  await page.setViewportSize({width:1440,height:960});
  await page.reload();
  await page.getByRole('button',{name:'Open portal assistant',exact:true}).click();
  await page.getByRole('button',{name:'What is my staff profile?',exact:true}).waitFor();
  await verify('signed-in privacy notice remains visible',()=>page.getByText('Personal information is shown only for your verified signed-in account.',{exact:true}).isVisible());
  await page.screenshot({path:'output/playwright/assistant-premium-staff.png'});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'output/playwright/assistant-premium-staff-mobile.png'});
  return checks;
}
